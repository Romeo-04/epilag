// Logo: a pixel frog face on a forest tile ("#" ink line, "+" paper face, "a" amber cheek glint).
export const LOGO = [16, [
  "..####....####..",
  ".#++++#..#++++#.",
  ".#+##+#..#+##+#.",
  ".#+##+####+##+#.",
  ".#++++++++++++#.",
  "#++++++++++++++#",
  "#+a++++++++++a+#",
  "#++##########++#",
  ".#++++++++++++#.",
  "..############..",
]];

const COLOR = { "#": "var(--i1, currentColor)", "+": "var(--i2, var(--forest-soft))", a: "var(--i3, var(--amber))" };

function paths(rows, ox, oy) {
  const out = {};
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      if (!COLOR[c]) { x++; continue; }
      let end = x;
      while (end < row.length && row[end] === c) end++;
      out[c] = (out[c] || "") + `M${x + ox} ${y + oy}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  return out;
}

/** SVG markup for an icon. `size` should be a whole multiple of the icon's grid (12 or 16). */
export function icon(name, { size, label, className = "" } = {}) {
  const spec = name === "logo" ? LOGO : ICONS[name];
  if (!spec) throw new Error(`unknown icon ${name}`);
  const [grid, rows] = spec;
  const w = Math.max(...rows.map((r) => r.length));
  const ox = Math.floor((grid - w) / 2), oy = Math.floor((grid - rows.length) / 2);
  const px = size ?? grid * 2;
  const body = Object.entries(paths(rows, ox, oy)).map(([c, d]) => `<path fill="${COLOR[c]}" d="${d}"/>`).join("");
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true" focusable="false"`;
  return `<svg class="px-icon ${className}" width="${px}" height="${px}" viewBox="0 0 ${grid} ${grid}" shape-rendering="crispEdges" ${a11y}>${body}</svg>`;
}

/** Replace every <i data-icon="name" data-size="24"></i> under root with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll("i[data-icon]").forEach((el) => {
    const size = el.dataset.size ? Number(el.dataset.size) : undefined;
    el.outerHTML = icon(el.dataset.icon, { size, label: el.getAttribute("aria-label") || undefined, className: el.className });
  });
}
